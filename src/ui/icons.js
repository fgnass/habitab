/** An icon as an <svg class="icon …"> element (24-unit Lucide geometry, stroke from CSS). */
window.icon = (name, cls = '') => {
  const s = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  s.setAttribute('viewBox', '0 0 24 24');
  s.setAttribute('class', `icon ${cls}`.trim());
  s.setAttribute('aria-hidden', 'true');
  s.innerHTML = LUCIDE[name] ?? '';
  return s;
};

// Static markup: <span data-icon="hand" class="…"></span> becomes the icon.
for (const el of document.querySelectorAll('[data-icon]')) el.replaceWith(window.icon(el.dataset.icon, el.className));
